//
// callClaude reuses the exact same env var (ANTHROPIC_API_KEY) and model
// (claude-sonnet-4-5) as lib/scorecard-draft-shared.cjs's own callClaude —
// intentionally not inventing a second pattern for the same thing.
async function callClaude(prompt) {
  const res = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: {
      'x-api-key': ANTHROPIC_API_KEY,
      'anthropic-version': '2023-06-01',
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      model: CLAUDE_MODEL,
      max_tokens: 500,
      messages: [{ role: 'user', content: prompt }],
    }),
  })
  const text = await res.text()
  let data
  try { data = JSON.parse(text) } catch { data = { raw: text } }
  if (!res.ok) throw new Error(`Claude API error: ${JSON.stringify(data)}`)
  const textBlock = (data.content || []).find((b) => b.type === 'text')
  if (!textBlock) throw new Error(`Claude API returned no text block: ${JSON.stringify(data)}`)
  return textBlock.text
}

// SHELF_LIFE_ALERT_THRESHOLD_DAYS / findNearExpiryStuckLines — added
// 2026-09-08 per Hill's same feedback: "Anything with less than 140 days
// that is getting skipped needs to get called as part of the Immediate
// Action Summary." "Getting skipped" = hold or blocked verdict (older
// stock correctly not shipping today) — these were NEVER fed into the
// summary before this change, since generateBiggestIssuesSummary only
// ever saw the violation list. A near-expiry hold/blocked lot could sit
// there indefinitely, risk expiring in the warehouse, and never once
// surface in the one section meant to flag urgent issues. Scoped to
// dateSemantic:'expiration' projects only, same as shelfLifeSuffix above —
// scans ALL orders (not just violations) for hold/blocked lines under the
// threshold, independent of whether the project has any violations today.
const SHELF_LIFE_ALERT_THRESHOLD_DAYS = 140

function findNearExpiryStuckLines(orders, project, asOfDate) {
  if (project?.dateSemantic !== 'expiration') return []
  const out = []
  for (const o of orders) {
    for (const line of (o.lines || [])) {
      const v = lineVerdict(line)
      if (v !== 'hold' && v !== 'blocked') continue
      const days = shelfLifeDaysRemaining(line.rem?.date, asOfDate)
      if (days == null || days >= SHELF_LIFE_ALERT_THRESHOLD_DAYS) continue
      out.push({ order: o, line, days })
    }
  }
  return out
}

// Formats one violating order for the prompt — same per-line detail
// (verdictCopy + severity) as the digest's own violation list, so the
// summary is grounded in exactly what a human reading the digest sees,
// not a separately-computed view that could disagree.
function formatViolationForPrompt(o, project, asOfDate) {
  const out = [`${o.id} — ${o.dest || 'dest unknown'}`]
  for (const line of (o.lines || [])) {
    if (lineVerdict(line) !== 'violation') continue
    const sev = lineSeverity(line)
    out.push(`  ${line.code}${line.desc ? ' ' + line.desc : ''}: ${verdictCopy(line, project, asOfDate)}${sev ? ` (${sev.toUpperCase()})` : ''}`)
  }
  return out.join('\n')
}

// Formats one near-expiry stuck line for the prompt — added 2026-09-08
// alongside findNearExpiryStuckLines above.
function formatStuckLineForPrompt({ order, line, days }, project, asOfDate) {
  const tag = days < 0 ? 'EXPIRED' : `${days}d SHELF LIFE LEFT`
  return `${order.id} — ${order.dest || 'dest unknown'} — ${line.code}${line.desc ? ' ' + line.desc : ''}: ${verdictCopy(line, project, asOfDate)} [${tag}]`
}

// aggregateLotActions/formatLotActionLine — added 2026-09-09 per Dan's
// feedback: the AI-written "Immediate Action Summary" paragraph, while
// synthesized well, packed multiple lots' worth of counts/dates into dense
// prose ("lot X ... 124 days ... 13+ orders ... lot Y ... 55 days ... 20+
// orders") that was hard to scan and, worse, risked the model mis-stating
// a count or date someone would then act on in Datex. Replaced the
// per-lot detail with a DETERMINISTIC, code-computed list — one block per
// distinct lot, exact order counts (no more "13+" hedging), sorted by
// urgency — so there's zero hallucination risk on the numbers a warehouse
// manager actually uses to go find and reallocate a pallet. The AI call
// (generateBiggestIssuesSummary, below) now only writes a short 1-2
// sentence PATTERN-level observation (chronic/systemic vs. one-off) —
// exactly the kind of judgment call an LLM is good at and a deterministic
// aggregation can't make — with the per-lot specifics handled entirely by
// this function instead.
//
// Groups by LOT NUMBER (not by order) across both violating orders and
// near-expiry stuck lines, since the same lot commonly recurs across many
// orders (see the PALDSD9 example that prompted this: lot 17526 alone hit
// 20+ orders) — a per-order list would just repeat the same lot's detail
// dozens of times, exactly what made the old format hard to scan.
function aggregateLotActions(violatingOrders, nearExpiryStuck, project, asOfDate) {
  const byLot = new Map()

  for (const o of violatingOrders) {
    for (const line of (o.lines || [])) {
      if (lineVerdict(line) !== 'violation') continue
      const lot = line.rem?.lot
      if (!lot) continue
      if (!byLot.has(lot)) {
        byLot.set(lot, {
          lot, code: line.code, desc: line.desc, location: line.rem.location || '',
          date: line.rem.date, orderIds: new Set(), maxSeverity: null, maxDaysOlder: 0,
          isViolation: true, isStuck: false, holdType: null,
        })
      }
      const entry = byLot.get(lot)
      entry.orderIds.add(o.id)
      const sev = lineSeverity(line)
      if (sev === 'critical') entry.maxSeverity = 'critical'
      else if (sev === 'warning' && entry.maxSeverity !== 'critical') entry.maxSeverity = 'warning'
      const d = lineDaysOlder(line)
      if (d > entry.maxDaysOlder) entry.maxDaysOlder = d
    }
  }

  for (const { order: o, line, days } of nearExpiryStuck) {
    const lot = line.rem?.lot
    if (!lot) continue
    if (!byLot.has(lot)) {
      byLot.set(lot, {
        lot, code: line.code, desc: line.desc, location: line.rem.location || '',
        date: line.rem.date, orderIds: new Set(), maxSeverity: null, maxDaysOlder: 0,
        isViolation: false, isStuck: false, holdType: null,
      })
    }
    const entry = byLot.get(lot)
    entry.orderIds.add(o.id)
    entry.isStuck = true
    entry.holdType = entry.holdType || line.rem.holdType || null
  }

  const list = [...byLot.values()].map(e => ({
    ...e,
    orderCount: e.orderIds.size,
    shelfLifeDays: project?.dateSemantic === 'expiration' ? shelfLifeDaysRemaining(e.date, asOfDate) : null,
  }))

  // Sort: anything with a known shelf-life countdown sorts by SOONEST TO
  // EXPIRE first regardless of violation/stuck status — that's the axis
  // that actually determines urgency (see the PALDSD9 example: a 4-day
  // lot needed to outrank a 74-day lot even though the 74-day one hit
  // more orders). Ties/no-shelf-life fall back to violation-before-stuck,
  // then severity, then order count.
  const sevRank = s => (s === 'critical' ? 0 : s === 'warning' ? 1 : 2)
  list.sort((a, b) => {
    if (a.shelfLifeDays != null && b.shelfLifeDays != null && a.shelfLifeDays !== b.shelfLifeDays) {
      return a.shelfLifeDays - b.shelfLifeDays
    }
    if (a.shelfLifeDays != null && b.shelfLifeDays == null) return -1
    if (a.shelfLifeDays == null && b.shelfLifeDays != null) return 1
    if (a.isViolation !== b.isViolation) return a.isViolation ? -1 : 1
    if (sevRank(a.maxSeverity) !== sevRank(b.maxSeverity)) return sevRank(a.maxSeverity) - sevRank(b.maxSeverity)
    return b.orderCount - a.orderCount
  })

  return list
}

function formatLotActionLine(entry, project) {
  const verb = dateVerb(project)
  const shelf = entry.shelfLifeDays != null
    ? (entry.shelfLifeDays < 0 ? `EXPIRED ${Math.abs(entry.shelfLifeDays)}d ago` : `${entry.shelfLifeDays}d shelf life left`)
    : null
  const parts = [entry.location || 'location unknown']
  parts.push(shelf || `${verb} ${entry.date}`)
  parts.push(`${entry.orderCount} order${entry.orderCount === 1 ? '' : 's'}`)
  if (entry.isViolation && entry.maxSeverity) parts.push(entry.maxSeverity.toUpperCase())
  if (entry.isStuck && !entry.isViolation) parts.push(`ON ${entry.holdType || 'HOLD'} — NEAR EXPIRY`)
  const icon = entry.isViolation ? '⚠' : '⏸'
  return `${icon} Lot ${entry.lot} — ${entry.code}${entry.desc ? ' ' + entry.desc : ''}\n   ${parts.join(' · ')}`
}

async function generateBiggestIssuesSummary(violatingOrders, nearExpiryStuck, project, asOfDate) {
  if (!ANTHROPIC_API_KEY) return null
  if (!violatingOrders.length && !nearExpiryStuck.length) return null
  const violationText = violatingOrders.length
    ? violatingOrders.map((o) => formatViolationForPrompt(o, project, asOfDate)).join('\n\n')
    : '(none today)'
  const stuckText = nearExpiryStuck.length
    ? nearExpiryStuck.map((entry) => formatStuckLineForPrompt(entry, project, asOfDate)).join('\n')
    : '(none)'
  // Prompt simplified 2026-09-09 — see aggregateLotActions above for why.
  // Deliberately asks for PATTERN judgment only (chronic/systemic vs.
  // one-off), not per-lot counts/dates — those are now computed
  // deterministically right below this in buildDigestBody, with zero risk
  // of the model mis-stating a number someone will act on in Datex.
  const prompt = `You are looking at today's FEFO (First-Expired-First-Out) rotation report for ${project.name} (${project.code}), a CSW-WI 3PL warehouse customer.

VIOLATIONS — newer stock shipping while older, unallocated, off-hold stock of the same material sits unused:
${violationText}

STUCK LOTS NEAR EXPIRATION — these are correctly NOT shipping today (on hold or not yet put away), so they are NOT FEFO violations, but each has under ${SHELF_LIFE_ALERT_THRESHOLD_DAYS} days of shelf life remaining and risks expiring while stuck in the warehouse:
${stuckText}

In exactly 1-2 short sentences, describe the overall PATTERN here for a warehouse operations manager — is this concentrated in a small number of chronic lots/locations that keep recurring across many orders (pointing to a systemic allocation-bypass or WMS rule issue), or is it spread across many one-off cases? Do NOT list individual lot numbers, dates, or order counts — those are shown separately in an exact, itemized list right after this. Just the pattern-level read, in plain direct language.`
  // Never let a Claude failure (rate limit, timeout, bad response) block
  // the digest itself from posting — the exhaustive list below is the
  // part that must always go out; this summary is additive context only.
  try {
    return await callClaude(prompt)
  } catch (e) {
    console.warn(`generateBiggestIssuesSummary failed for ${project.code}: ${e.message}`)
    return null
  }
}

async function buildDigestBody(orders, project, dateObj) {
  const lines = []
  lines.push(`FEFO Rotation — ${project.name} (${project.code})`)
  lines.push(APP_URL)
  lines.push('CSW Operations Hub')
  lines.push(project.closedOrders
    ? `Reviewing closed orders shipped: ${formatHeaderDate(dateObj)}`
    : `Live snapshot: ${formatHeaderDate(dateObj)}`)
  lines.push('')

  if (orders.length === 0) {
    lines.push(project.closedOrders
      ? 'No closed orders shipped on that date.'
      : 'No orders in the FEFO window for this project on that date.')
    return lines.join('\n')
  }

  const byVerdict = { violation: [], stale: [], hold: [], blocked: [], clean: [] }
  for (const o of orders) byVerdict[orderVerdict(o)].push(o)

  const critical = byVerdict.violation.filter(o => orderSeverity(o) === 'critical').length
  const warning = byVerdict.violation.filter(o => orderSeverity(o) === 'warning').length
  const undated = undatedLotCount(orders)

  const summaryParts = []
  if (byVerdict.stale.length) summaryParts.push(`${byVerdict.stale.length} stale`)
  if (byVerdict.hold.length) summaryParts.push(`${byVerdict.hold.length} on hold`)
  if (byVerdict.blocked.length) summaryParts.push(`${byVerdict.blocked.length} in receiving`)
  lines.push(project.closedOrders
    ? `${orders.length} order${orders.length === 1 ? '' : 's'} shipped · ${byVerdict.clean.length} in FEFO order${summaryParts.length ? ' · ' + summaryParts.join(' · ') : ''}`
    : `${orders.length} order${orders.length === 1 ? '' : 's'} in rotation window · ${byVerdict.clean.length} clean${summaryParts.length ? ' · ' + summaryParts.join(' · ') : ''}`)
  lines.push('')

  const divider = '─'.repeat(28)
  lines.push(divider)
  if (byVerdict.violation.length > 0) {
    const sevBits = [critical ? `${critical} CRITICAL` : '', warning ? `${warning} WARNING` : ''].filter(Boolean).join(' · ')
    lines.push(`**⚠ ${byVerdict.violation.length} VIOLATION${byVerdict.violation.length === 1 ? '' : 'S'}${sevBits ? ` (${sevBits})` : ''}**`)
  } else {
    lines.push('**✓ 0 VIOLATIONS**')
  }
  lines.push(divider)
  lines.push('')

  // Immediate Action Summary (was "Biggest issues today", renamed
  // 2026-09-08 to match Hill's own terminology). Sits between the badge
  // and the exhaustive list below on purpose: quick synthesis first for
  // someone skimming, full detail still right there for anyone who wants
  // to dig in — the exhaustive list is NOT replaced or shortened by this.
  //
  // Restructured 2026-09-09 per Dan's feedback: the old AI-written prose
  // packed every lot's counts/dates into dense paragraphs that were hard
  // to scan and risked the model mis-stating a number. Now: one short
  // AI-written PATTERN sentence (chronic/systemic vs. one-off — genuine
  // LLM judgment call), followed by a deterministic, code-computed list
  // (aggregateLotActions/formatLotActionLine above) — one block per
  // distinct lot, exact order counts, sorted soonest-to-expire first, zero
  // hallucination risk on the numbers someone acts on in Datex.
  const nearExpiryStuck = findNearExpiryStuckLines(orders, project, dateObj)
  if (byVerdict.violation.length > 0 || nearExpiryStuck.length > 0) {
    const summary = await generateBiggestIssuesSummary(byVerdict.violation, nearExpiryStuck, project, dateObj)
    const lotActions = aggregateLotActions(byVerdict.violation, nearExpiryStuck, project, dateObj)
    if (summary || lotActions.length) {
      lines.push('**Immediate Action Summary:**')
      if (summary) { lines.push(summary.trim()); lines.push('') }
      for (const entry of lotActions) {
        lines.push(formatLotActionLine(entry, project))
        lines.push('')
      }
    }
  }

  if (byVerdict.violation.length) {
    lines.push(project.closedOrders ? 'Shipped out of FEFO order:' : 'Violations:')
    lines.push('')
    for (const o of byVerdict.violation) {
      lines.push(`• ${o.id} — ${o.dest || 'dest unknown'}${o.appt && o.appt !== '—' ? ` — appt ${o.appt}` : ''}`)
      // Per-line detail (added 2026-08-06, Dan's approved mockup) — same
      // wording as the live tab's OrderCard/SkuLineRow, so Front and the
      // app never disagree. Only the actually-violating lines on this
      // order get a detail line; a multi-SKU order with one bad line
      // doesn't repeat detail for its clean lines.
      for (const line of (o.lines || [])) {
        if (lineVerdict(line) !== 'violation') continue
        const sev = lineSeverity(line)
        lines.push(`  ${line.code}${line.desc ? ' ' + line.desc : ''}: ${verdictCopy(line, project, dateObj)}${sev ? ` (${sev.toUpperCase()})` : ''}`)
      }
      lines.push('')
    }
  }
  if (byVerdict.hold.length) {
    lines.push('On hold (older lot correctly skipped):')
    lines.push('')
    for (const o of byVerdict.hold) { lines.push(`• ${o.id} — ${o.dest || 'dest unknown'}`); lines.push('') }
  }
  if (byVerdict.blocked.length) {
    lines.push('In receiving / not put away:')
    lines.push('')
    for (const o of byVerdict.blocked) { lines.push(`• ${o.id} — ${o.dest || 'dest unknown'}`); lines.push('') }
  }
  if (byVerdict.stale.length) {
    lines.push('Stale (past appointment, still allocated):')
    lines.push('')
    for (const o of byVerdict.stale) { lines.push(`• ${o.id} — ${o.dest || 'dest unknown'}`); lines.push('') }
  }
  if (undated > 0) {
    lines.push(`⚠ ${undated} lot${undated === 1 ? '' : 's'} with no parseable date in this window — verify in Datex.`)
    lines.push('')
  }
  if (!byVerdict.violation.length && !byVerdict.stale.length && !byVerdict.hold.length && !byVerdict.blocked.length && undated === 0) {
    lines.push('✓ All orders pulling oldest available stock — no other issues.')
    lines.push('')
  }
  while (lines.length && lines[lines.length - 1] === '') lines.pop()
  return lines.join('\n')
}

async function runForProject({ settingsRow, project, dateObj, isManualTest }) {
  const conversationId = settingsRow?.front_conversation_id
  if (!conversationId) {
    return { ok: false, reason: `No front_conversation_id configured for ${project.code}`, project: project.code }
  }

  const date = isoDate(dateObj)

  // dayCount/closedDayBucket — closedOrders (JDF) still uses its own
  // backward window, unchanged. Open-order (non-closedOrders) projects no
  // longer need a day-window at all (2026-08-06 — see fefo-orders.cjs's
  // file header "Open-order date filtering removed"): fefo-orders.cjs
  // ignores date bounds entirely for these now and always returns day=0,
  // so dayCount=1 with no per-day filtering is sufficient — every order it
  // returns IS the live snapshot.
  let dayCount = 1
  let closedDayBucket = 0
  if (project.closedOrders) {
    closedDayBucket = 0
  }

  const ordersRes = await fetch(`${SITE_URL}/.netlify/functions/fefo-orders`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ facility: project.facility, projectIds: [project.id], dayCount }),
  })
  const ordersText = await ordersRes.text()
  let ordersJson
  try { ordersJson = JSON.parse(ordersText) } catch { ordersJson = { raw: ordersText } }
  if (!ordersRes.ok) {
    return { ok: false, reason: 'fefo-orders failed', detail: ordersJson, project: project.code }
  }

  const allOrders = ordersJson.ordersByProject?.[project.id] || []
  const targetOrders = project.closedOrders ? allOrders.filter(o => o.day === closedDayBucket) : allOrders

  const body = await buildDigestBody(targetOrders, project, dateObj)

  const frontRes = await fetch(`https://api2.frontapp.com/conversations/${conversationId}/comments`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${FRONT_TOKEN}`, 'Content-Type': 'application/json', Accept: 'application/json' },
    body: JSON.stringify({ body }),
  })
  const frontText = await frontRes.text()
  let frontJson
  try { frontJson = JSON.parse(frontText) } catch { frontJson = { raw: frontText } }
  if (!frontRes.ok) {
    return { ok: false, reason: 'Front API error posting comment', detail: frontJson, project: project.code }
  }

  if (!isManualTest) {
    await sbPatch(`prepick_notify_settings?facility=eq.${project.facility}&dashboard_type=eq.fefo_${project.id}`, { last_sent_date: date })
  }

  return { ok: true, date, project: project.code, conversationId, commentId: frontJson.id, orderCount: targetOrders.length }
}

