const VERDICT_PRECEDENCE = { violation: 0, stale: 1, hold: 2, blocked: 3, clean: 4 }

function lineVerdict(line) {
  if (!line?.ship?.length) return 'clean'
  const datedShip = line.ship.filter(s => !s.dateUnknown)
  if (!datedShip.length) return 'clean'
  const oldKDay = Math.min(...datedShip.map(s => s.kDay ?? s.k))
  const rem = line.rem
  const remKDay = rem?.kDay ?? rem?.k
  if (rem && !rem.dateUnknown && rem.lps > 0 && remKDay != null && remKDay < oldKDay) {
    if (rem.hold) return 'hold'
    if (rem.locationBlocked) return 'blocked'
    return 'violation'
  }
  return 'clean'
}

function orderVerdict(order) {
  const verdicts = (order.lines || []).map(lineVerdict)
  const worst = verdicts.length
    ? verdicts.reduce((a, b) => VERDICT_PRECEDENCE[a] <= VERDICT_PRECEDENCE[b] ? a : b)
    : 'clean'
  if (order.past && worst !== 'violation') return 'stale'
  return worst
}

function parseDisplayDate(display) {
  if (!display || typeof display !== 'string') return null
  const m = display.match(/^(\d{1,2})\/(\d{1,2})\/(\d{1,4})$/)
  if (!m) return null
  const month = Number(m[1]), day = Number(m[2])
  let year = Number(m[3]); if (year < 100) year += 2000
  const d = new Date(Date.UTC(year, month - 1, day))
  return Number.isNaN(d.getTime()) ? null : d
}

function lineDaysOlder(line) {
  if (lineVerdict(line) !== 'violation') return 0
  if (!line?.ship?.length || !line?.rem?.date) return 0
  const datedShip = line.ship.filter(s => !s.dateUnknown)
  if (!datedShip.length) return 0
  const oldShip = datedShip.reduce((a, b) => a.k < b.k ? a : b)
  const shipDate = parseDisplayDate(oldShip.date)
  const remDate = parseDisplayDate(line.rem.date)
  if (!shipDate || !remDate) return 0
  return Math.max(0, Math.round((shipDate.getTime() - remDate.getTime()) / 86400000))
}

function orderMaxDaysOlder(order) {
  let max = 0
  for (const line of (order.lines || [])) { const d = lineDaysOlder(line); if (d > max) max = d }
  return max
}

function orderSeverity(order) {
  const days = orderMaxDaysOlder(order)
  if (days === 0) return null
  return days >= 4 ? 'critical' : 'warning'
}

// lineSeverity — added 2026-08-06 alongside verdictCopy above, for the same
// per-line digest detail. Mirrors orderSeverity's threshold (4 days) but
// per LINE rather than per order, matching src/lib/fefo.js's lineSeverity.
function lineSeverity(line) {
  const days = lineDaysOlder(line)
  if (days === 0) return null
  return days >= 4 ? 'critical' : 'warning'
}

function undatedLotCount(orders) {
  const lots = new Set()
  for (const o of orders) {
    for (const line of (o.lines || [])) {
      for (const s of (line.ship || [])) if (s.dateUnknown && s.lot) lots.add(s.lot)
      for (const u of (line.undatedOnHand || [])) if (u.lot) lots.add(u.lot)
    }
  }
  return lots.size
}

// verdictCopy/dateVerb/locSuffix — added 2026-08-06 per Dan's approved
// mockup (Hill/Sam/Dan FEFO review call): the digest's violation list now
// includes the same per-line detail the live tab shows, rather than a
// separate, hand-written summary that could drift from the app's own
// wording. Ported verbatim from src/lib/fefo.js's verdictCopy/dateVerb —
// takes a project OBJECT directly (we already have one in scope here)
// rather than looking one up by id the way the client's dateVerb(projId)
// does.
function dateVerb(project) {
  if (project?.dateSemantic === 'expiration') return 'expiring'
  if (project?.dateSemantic === 'received')   return 'received'
  if (project?.dateSemantic === 'man')        return 'manufactured'
  return 'packed'
}

function locSuffix(rem) {
  if (!rem?.location) return ''
  return ` at ${rem.location}`
}

// lotSuffix — added 2026-08-31 per Hill Hamrick's Front feedback (PALVI9
// digest): the violation text named the MATERIAL ("31172 CRAVN TC FOUR
// CHEESE 21.06OZ") but never the actual LOT NUMBER of the stuck LPs —
// Hill had to ask "ie whats the lot?" since there was nothing to look up
// in Datex from the message alone. Same fix applied to src/lib/fefo.js's
// verdictCopy so the live tab's inline verdict text and the digest never
// disagree.
function lotSuffix(rem) {
  if (!rem?.lot) return ''
  return ` (lot ${rem.lot})`
}

// shelfLifeDaysRemaining/shelfLifeSuffix — added 2026-09-08 per Hill's
// follow-up on the same PALVI9 conversation (cnv_1c0ok3dg): "can you add
// the expiration date and shelf life days remaining to this message
// whenever specific lots are referenced." The expiration DATE was already
// shown for expiration-semantic projects (dateVerb returns 'expiring' and
// the date itself is already in the sentence) — what was missing was the
// countdown. Only meaningful for dateSemantic:'expiration' projects (e.g.
// Palermo's); pack/receive/man-date projects don't have an expiration to
// count down to, so this is a no-op for them. asOfDate defaults to "now"
// but buildDigestBody passes its own dateObj through explicitly so the
// digest's countdown matches the header's "as of" date rather than the
// exact millisecond the Claude call happens to run.
function shelfLifeDaysRemaining(remDateDisplay, asOfDate) {
  const expDate = parseDisplayDate(remDateDisplay)
  if (!expDate || !asOfDate) return null
  const asOfMidnight = new Date(Date.UTC(asOfDate.getUTCFullYear(), asOfDate.getUTCMonth(), asOfDate.getUTCDate()))
  return Math.round((expDate.getTime() - asOfMidnight.getTime()) / 86400000)
}

function shelfLifeSuffix(remDateDisplay, asOfDate, project) {
  if (project?.dateSemantic !== 'expiration') return ''
  const days = shelfLifeDaysRemaining(remDateDisplay, asOfDate)
  if (days == null) return ''
  return days < 0 ? ` (expired ${Math.abs(days)}d ago)` : ` (${days}d shelf life left)`
}

function verdictCopy(line, project, asOfDate = new Date()) {
  const verb = dateVerb(project)
  const v = lineVerdict(line)
  if (v === 'violation') {
    const datedShip = line.ship.filter(s => !s.dateUnknown)
    const oldShip = datedShip.reduce((a, b) => a.k < b.k ? a : b)
    const stockUnit = line.rem.lps > 0 ? `${line.rem.lps} LP${line.rem.lps === 1 ? '' : 's'}` : 'stock'
    const loc = locSuffix(line.rem)
    const lot = lotSuffix(line.rem)
    const shelf = shelfLifeSuffix(line.rem.date, asOfDate, project)
    const days = lineDaysOlder(line)
    const drift = days > 0 ? ` (${days} day${days === 1 ? '' : 's'} older)` : ''
    return `Out of rotation${drift} — ${stockUnit}${lot} ${verb} ${line.rem.date}${shelf} (${line.rem.cases} cs)${loc} sit unallocated and off hold, older than the ${oldShip.date} stock on this order. Swap them in before it ships.`
  }
  if (v === 'hold') {
    return `Older stock exists${lotSuffix(line.rem)} (${verb} ${line.rem.date}${shelfLifeSuffix(line.rem.date, asOfDate, project)}, ${line.rem.lps} LP${line.rem.lps === 1 ? '' : 's'}) but it is on ${line.rem.holdType || 'hold'}, so it is correctly skipped. Clear the hold before it can ship in rotation.`
  }
  if (v === 'blocked') {
    const where = line.rem.location ? `in ${line.rem.location}` : 'in a non-allocatable location (receiving, staging, dock, etc.)'
    return `Older stock exists${lotSuffix(line.rem)} (${verb} ${line.rem.date}${shelfLifeSuffix(line.rem.date, asOfDate, project)}, ${line.rem.lps} LP${line.rem.lps === 1 ? '' : 's'}) but it hasn't been put away yet — sitting ${where}, so it is correctly skipped. Move it to an allocatable bin before it can ship in rotation.`
  }
  if (!line.rem || line.rem.lps === 0) {
    return 'In rotation — the oldest stock on hand is shipping first… fully cleared.'
  }
  return 'In rotation — the oldest stock on hand is shipping first.'
}

