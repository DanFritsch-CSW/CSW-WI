// Shared core for the FEFO nightly digest — split out 2026-07-30 from
// fefo-digest-run.cjs.
//
// WHY THIS SPLIT EXISTS: Netlify does not allow direct HTTP invocation of
// any function that has a `schedule` set in netlify.toml — confirmed via
// Netlify's own docs ("Scheduled functions only run on their schedule for
// published deploys ... you can't invoke them directly with a URL") and
// reproduced live: "Send test digest now" started returning an empty-body,
// text/plain, Server: Netlify 403 for EVERY FEFO project (not just the
// Palermo's/CAL ones it was first noticed on — confirmed by reproducing it
// on FAIOA5 too), with no corresponding invocation ever showing up in the
// function's own logs. That 403 is generated by Netlify's platform before
// the function code runs at all — neither fefo-digest-run.cjs nor
// fefo-orders.cjs can structurally produce a 403 under any code path, so
// it was never our own logic rejecting the request.
//
// Fix: the function that CARRIES the `schedule` (fefo-digest-run.cjs) is
// now scheduled-tick-only. A separate function with NO schedule entry in
// netlify.toml (fefo-digest-test.cjs) handles manual "Send test digest
// now" clicks instead. Both require this shared module so the actual
// digest-building logic (verdict engine, message formatting, Front
// posting) lives in exactly one place and can't drift between the two
// entry points.
//
// Everything below is otherwise unchanged from the original
// fefo-digest-run.cjs — see that file's original header (preserved in git
// history) for the fuller feature history (per-project settings rows,
// next-business-day content date, JDF's closedOrders variant, etc).

